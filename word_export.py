import re
from docx import Document


def clean_text(s):
    if not s:
        return ""
    s = s.replace("\\(", "(").replace("\\)", ")")
    s = s.replace("\\[", "[").replace("\\]", "]")
    s = s.replace("\\$", "$").replace("\\%", "%")
    s = s.replace("\\_", "_").replace("\\&", "&")
    s = s.replace("\\#", "#").replace("\\{", "{").replace("\\}", "}")
    s = s.replace("\\", "")
    s = re.sub(r"^\s*\d+\\?\.\s*", "", s)
    return s.strip()


def add_line(doc, line):
    p = doc.add_paragraph()
    run = p.add_run(line)
    if "|" in line or "\t" in line:
        run.font.name = "Consolas"


def export_paper(items, path="variant_paper.docx"):
    doc = Document()
    doc.add_heading("Variant Exam Paper", level=1)
    for i, it in enumerate(items, 1):
        q = clean_text(it.get("new_question", ""))
        doc.add_heading(f"Question {i}", level=2)
        for line in q.split("\n"):
            line = line.strip()
            if line:
                add_line(doc, line)
        for opt in it.get("new_options", []):
            if opt:
                add_line(doc, clean_text(opt))
        doc.add_paragraph("")
    doc.save(path)
    return path


def export_answers(items, path="answer_key.docx"):
    doc = Document()
    doc.add_heading("Answer Key and Explanations", level=1)
    for i, it in enumerate(items, 1):
        doc.add_heading(f"Question {i}", level=2)
        ans = clean_text(it.get("answer", ""))
        exp = clean_text(it.get("explanation", ""))
        add_line(doc, f"Answer: {ans}")
        if exp:
            for line in exp.split("\n"):
                line = line.strip()
                if line:
                    add_line(doc, line)
        doc.add_paragraph("")
    doc.add_paragraph("This paper was generated by AI. Please verify all answers.")
    doc.save(path)
    return path